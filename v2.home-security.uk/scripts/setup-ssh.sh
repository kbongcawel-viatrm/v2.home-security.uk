#!/usr/bin/env bash
# Set up hardened SSH configuration for GitHub Actions
# This script configures SSH with security hardening for connecting to target hosts
#
# Usage:
#   ./scripts/setup-ssh.sh <ssh_key> <target_host> <target_user> [target_port]
#
# Environment variables:
#   SSH_KEY       - SSH private key content (required)
#   TARGET_HOST   - Target host IP/hostname (required)
#   TARGET_USER   - SSH user (required)
#   TARGET_PORT   - SSH port (default: 22)
#
# Example:
#   export SSH_KEY="$(cat ~/.ssh/id_ed25519)"
#   export TARGET_HOST="192.168.1.100"
#   export TARGET_USER="kim"
#   ./scripts/setup-ssh.sh

set -euo pipefail

# Configuration
SSH_DIR="${HOME}/.ssh"
SSH_KEY_FILE="${SSH_DIR}/id_ed25519"
SSH_CONFIG_FILE="${SSH_DIR}/config"
KNOWN_HOSTS_FILE="${SSH_DIR}/known_hosts"

TARGET_HOST="${TARGET_HOST:-${2:-}}"
TARGET_USER="${TARGET_USER:-${3:-}}"
TARGET_PORT="${TARGET_PORT:-${4:-22}}"
SSH_KEY_CONTENT="${SSH_KEY:-${1:-}}"

# Validate inputs
if [[ -z "$SSH_KEY_CONTENT" ]]; then
    echo "::error::SSH key is required (set SSH_KEY env var or pass as first argument)" >&2
    exit 1
fi

if [[ -z "$TARGET_HOST" ]]; then
    echo "::error::Target host is required (set TARGET_HOST env var or pass as second argument)" >&2
    exit 1
fi

if [[ -z "$TARGET_USER" ]]; then
    echo "::error::Target user is required (set TARGET_USER env var or pass as third argument)" >&2
    exit 1
fi

echo "=== Setting up hardened SSH configuration ==="
echo "Target: ${TARGET_USER}@${TARGET_HOST}:${TARGET_PORT}"

# Create SSH directory with secure permissions
mkdir -p "$SSH_DIR"
chmod 700 "$SSH_DIR"

# Write SSH private key
umask 077
echo "$SSH_KEY_CONTENT" > "$SSH_KEY_FILE"
chmod 600 "$SSH_KEY_FILE"
echo "SSH key written to $SSH_KEY_FILE"

# Create hardened SSH config
cat > "$SSH_CONFIG_FILE" << EOF
# Hardened SSH Configuration - Generated by setup-ssh.sh
# Generated at: $(date -u +%Y-%m-%dT%H:%M:%SZ)

# Global hardening - applies to all hosts
Host *
    # Authentication - public key only
    PreferredAuthentications publickey
    PasswordAuthentication no
    ChallengeResponseAuthentication no
    KbdInteractiveAuthentication no
    PubkeyAuthentication yes
    
    # Strong host key algorithms only
    HostKeyAlgorithms ssh-ed25519-cert-v01@openssh.com,ssh-ed25519,rsa-sha2-512-cert-v01@openssh.com,rsa-sha2-512,rsa-sha2-256-cert-v01@openssh.com,rsa-sha2-256
    
    # Strong ciphers only (ChaCha20 and AES-GCM preferred)
    Ciphers chacha20-poly1305@openssh.com,aes256-gcm@openssh.com,aes128-gcm@openssh.com,aes256-ctr,aes192-ctr,aes128-ctr
    
    # Strong key exchange only
    KexAlgorithms curve25519-sha256,curve25519-sha256@libssh.org,diffie-hellman-group18-sha512,diffie-hellman-group16-sha512,diffie-hellman-group-exchange-sha256
    
    # Strong MACs only (encrypt-then-MAC)
    MACs hmac-sha2-512-etm@openssh.com,hmac-sha2-256-etm@openssh.com,hmac-sha2-512,hmac-sha2-256
    
    # Security settings
    Compression no
    ForwardAgent no
    ForwardX11 no
    ForwardX11Trusted no
    PermitLocalCommand no
    GSSAPIAuthentication no
    GSSAPIDelegateCredentials no
    
    # Connection settings
    ConnectTimeout 10
    ConnectionAttempts 3
    ServerAliveInterval 30
    ServerAliveCountMax 3
    
    # Host verification
    StrictHostKeyChecking yes
    CheckHostIP yes
    HashKnownHosts yes
    
    # Logging
    LogLevel ERROR

# Target host configuration
Host ${TARGET_HOST} target target-host
    HostName ${TARGET_HOST}
    User ${TARGET_USER}
    Port ${TARGET_PORT}
    IdentityFile ${SSH_KEY_FILE}
    IdentitiesOnly yes
EOF

chmod 600 "$SSH_CONFIG_FILE"
echo "Hardened SSH config written to $SSH_CONFIG_FILE"

# Scan and add target host key to known_hosts
echo "=== Scanning target host key ==="
if ssh-keyscan -p "$TARGET_PORT" -t ed25519,rsa "$TARGET_HOST" >> "$KNOWN_HOSTS_FILE" 2>/dev/null; then
    echo "Host key added to $KNOWN_HOSTS_FILE"
    # Show fingerprint for verification
    ssh-keygen -lf "$KNOWN_HOSTS_FILE" 2>/dev/null | grep "$TARGET_HOST" || true
else
    echo "::warning::Could not scan host key - StrictHostKeyChecking will fail on first connection"
    echo "Manually verify and add the host key:"
    echo "  ssh-keyscan -p $TARGET_PORT $TARGET_HOST >> $KNOWN_HOSTS_FILE"
fi

chmod 644 "$KNOWN_HOSTS_FILE" 2>/dev/null || true

# Test the connection
echo ""
echo "=== Testing SSH connection ==="
if ssh -o BatchMode=yes -o ConnectTimeout=10 "${TARGET_USER}@${TARGET_HOST}" "echo 'SSH connection successful' && hostname && whoami"; then
    echo ""
    echo "=== SSH setup complete ==="
    echo "You can now use: ssh ${TARGET_USER}@${TARGET_HOST}"
    exit 0
else
    echo ""
    echo "::error::SSH connection test failed" >&2
    echo "Check:" >&2
    echo "  1. Target host is reachable: ping $TARGET_HOST" >&2
    echo "  2. SSH server is running on target: nc -zv $TARGET_HOST $TARGET_PORT" >&2
    echo "  3. SSH key is authorized on target host" >&2
    echo "  4. Firewall allows SSH connections" >&2
    exit 1
fi
