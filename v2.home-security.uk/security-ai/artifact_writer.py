"""Build review-only security artifacts from validated worker recommendations."""

from __future__ import annotations

import hashlib
import ipaddress
import json
import os
import re
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


SEVERITY_ORDER = {
    "informational": 0,
    "info": 0,
    "low": 1,
    "medium": 2,
    "high": 3,
    "critical": 4,
}
MIN_SID = 1_000_000
MAX_SID = 1_999_999


def _severity(record: dict[str, Any]) -> str:
    analysis = record.get("analysis") or {}
    candidates = [analysis.get("overall_severity"), analysis.get("severity")]
    findings = analysis.get("findings", [])
    if isinstance(findings, list):
        candidates.extend(
            finding.get("severity")
            for finding in findings
            if isinstance(finding, dict)
        )
    normalized = [str(value).strip().lower() for value in candidates if value]
    return max(normalized, key=lambda value: SEVERITY_ORDER.get(value, 0), default="low")


def _valid_suricata_rule(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    rule = value.strip()
    if (not rule.startswith("alert ") or len(rule) > 2000 or "\n" in rule or "\r" in rule
            or not re.match(r"^alert\s+(tcp|udp|icmp|ip|http|dns)\s", rule, re.IGNORECASE)):
        return False
    if not rule.endswith(")") or not re.search(r"\bsid:(\d+);", rule):
        return False
    sid = int(re.search(r"\bsid:(\d+);", rule).group(1))
    return MIN_SID <= sid <= MAX_SID and ";" in rule


def _public_ipv4(value: Any) -> str | None:
    if not isinstance(value, str):
        return None
    try:
        address = ipaddress.ip_address(value.strip())
    except ValueError:
        return None
    if address.version != 4 or not address.is_global:
        return None
    return str(address)


def build_artifacts(record: dict[str, Any]) -> dict[str, Any]:
    """Return deterministic contents for the four security-agent artifact files."""
    analysis = record.get("analysis") if isinstance(record.get("analysis"), dict) else {}
    severity = _severity(record)
    proposals = analysis.get("proposed_changes", [])
    proposals = proposals if isinstance(proposals, list) else []

    rules: list[str] = []
    seen_sids: set[int] = set()
    blocked_ips: set[str] = set()
    for proposal in proposals:
        if not isinstance(proposal, dict):
            continue
        if proposal.get("target") == "suricata":
            rule = proposal.get("rule")
            if not _valid_suricata_rule(rule):
                continue
            sid = int(re.search(r"\bsid:(\d+);", rule).group(1))
            if sid not in seen_sids:
                seen_sids.add(sid)
                rules.append(rule.strip())
        elif proposal.get("target") == "firewalld" and severity in ("high", "critical"):
            if proposal.get("block_type", "ip") != "ip":
                continue
            address = _public_ipv4(proposal.get("blocked_ip"))
            if address:
                blocked_ips.add(address)

    rules_text = "# Generated by security-ai; review before use.\n"
    rules_text += f"# Severity: {severity}; status: draft-only\n"
    if rules:
        rules_text += "\n".join(rules) + "\n"
    else:
        rules_text += "# No validated Suricata alert rules in this analysis.\n"

    ips_text = "# Generated by security-ai; review before use.\n"
    ips_text += f"# Severity: {severity}; status: draft-only\n"
    ips_text += "\n".join(sorted(blocked_ips))
    if blocked_ips:
        ips_text += "\n"
    else:
        ips_text += "# No eligible public IPv4 blocks (blocks require high/critical severity).\n"

    firewall_lines = [
        "#!/bin/sh",
        "# Generated draft only. Never execute this file; manual review is required.",
        "# Contains only narrow IPv4 source rich rules; does not change zones or defaults.",
        "set -eu",
    ]
    for address in sorted(blocked_ips):
        rich_rule = f"rule family=ipv4 source address={address} drop"
        firewall_lines.append(
            "firewall-cmd --permanent --zone=public --add-rich-rule='" + rich_rule + "'"
        )
    if blocked_ips:
        firewall_lines.append("firewall-cmd --reload")
    else:
        firewall_lines.append("# No commands generated: no eligible high/critical IP proposals.")
    firewall_text = "\n".join(firewall_lines) + "\n"

    generated_at = record.get("timestamp") or datetime.now(timezone.utc).isoformat()
    content_hash = hashlib.sha256(
        json.dumps(record, sort_keys=True, ensure_ascii=False, default=str).encode("utf-8")
    ).hexdigest()
    manifest = {
        "version": 1,
        "agent": "security-ai",
        "status": "draft_only",
        "generated_at": generated_at,
        "analysis_id": content_hash,
        "severity": severity,
        "event_count": int(record.get("event_count", 0) or 0),
        "event_refs": record.get("event_refs", []),
        "artifacts": {
            "suricata": {"path": "home-security.rules", "rule_count": len(rules)},
            "fail2ban": {"path": "blocked-ips.txt", "ip_count": len(blocked_ips), "integrated": False},
            "firewalld": {"path": "firewall-draft.sh", "ip_count": len(blocked_ips), "executable": False},
        },
        "deployment_policy": {
            "low_or_informational": "no automated blocking; Suricata alerts remain review-only",
            "medium": "Suricata alert rules only",
            "high_or_critical": "Suricata alerts plus narrowly scoped public IPv4 block drafts",
            "automatic_application": False,
        },
    }
    return {
        "home-security.rules": rules_text,
        "blocked-ips.txt": ips_text,
        "firewall-draft.sh": firewall_text,
        "manifest.json": json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
    }


def artifacts_for_manifest(manifest: dict[str, Any], artifact_dir: str | Path) -> list[dict[str, str]]:
    """Bind selected artifacts to their worker outputs and host deployment paths."""
    files = {
        "suricata": ("home-security.rules", "/etc/suricata/rules/home-security.rules"),
        "fail2ban": ("blocked-ips.txt", "/etc/fail2ban/blocked-ips.txt"),
        "firewalld": ("firewall-draft.sh", "/etc/firewalld/firewall-draft.sh"),
    }
    selected = []
    counts = manifest.get("artifacts", {})
    for name, (filename, destination) in files.items():
        item = counts.get(name, {}) if isinstance(counts, dict) else {}
        count = item.get("rule_count", item.get("ip_count", 0)) if isinstance(item, dict) else 0
        enabled = count > 0 and (
            (name == "suricata" and manifest.get("severity") in ("medium", "high", "critical"))
            or (name in ("fail2ban", "firewalld") and manifest.get("severity") in ("high", "critical"))
        )
        if enabled:
            selected.append({
                "name": name,
                "source": f"{Path(artifact_dir)}/{filename}",
                "dest": destination,
                "mode": "0600" if name != "suricata" else "0644",
            })
    return selected


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent, text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            output.write(text)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(temp_name, 0o644)
        os.replace(temp_name, path)
    finally:
        if os.path.exists(temp_name):
            os.unlink(temp_name)


def write_artifacts(record: dict[str, Any], output_dir: str | Path) -> dict[str, Any]:
    """Atomically publish content files first and the manifest last as commit marker."""
    contents = build_artifacts(record)
    root = Path(output_dir)
    for name in ("home-security.rules", "blocked-ips.txt", "firewall-draft.sh"):
        _atomic_write(root / name, contents[name])
    manifest = json.loads(contents["manifest.json"])
    manifest["deployable_artifacts"] = artifacts_for_manifest(manifest, root)
    contents["manifest.json"] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    _atomic_write(root / "manifest.json", contents["manifest.json"])
    return json.loads(contents["manifest.json"])